// QA: CTAs + booking + returning visitor. node scripts/test-cta.mjs <baseUrl> <outDir> [width]
import { chromium } from "@playwright/test";
const [base = "http://localhost:3457", out = ".", w = "1440"] = process.argv.slice(2);
const answers = { name: "Fade Factory", services: "a barbershop", location: "Manchester", q1: "Skin fades, beard trims and hot towel shaves", q2: "Local customers looking for a fresh cut", q3: "Precise fades and a relaxed welcome", q4Skipped: true, q5: "Book an appointment", q6: "Bold, modern and welcoming", q7: { mode: "colours", palette: ["#17324D", "#D8A84E"] } };
const gen = await fetch(`${base}/api/concept/generate`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ answers }) }).then((r) => r.json());
const state = { state: { pendingPrompt: null, stage: "preview", step: "preview", answers, attempt: 0, messageCount: 9, messages: [], contact: { name: "Alex Taylor", email: "alex@example.com", phone: "07700 900123", marketingOptIn: false }, content: gen.data, completedAt: new Date().toISOString(), builtAt: null, booking: null, logo: null }, version: 2 };
const b = await chromium.launch({ channel: "chromium" });
const p = await b.newPage({ viewport: { width: +w, height: 900 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.evaluate((s) => localStorage.setItem("rc-concept", JSON.stringify(s)), state);
await p.reload({ waitUntil: "networkidle" });
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/cta-${w}-0-home-returning.png` });
await p.getByRole("link", { name: /already got a homepage concept/ }).click();
await p.waitForURL("**/concept");
await p.waitForTimeout(1000);
await p.screenshot({ path: `${out}/cta-${w}-1-welcome.png` });
await p.getByRole("button", { name: "Get this built" }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/cta-${w}-2-built.png` });
console.log("built text:", (await p.locator("main [role=status]").innerText()).replace(/\n/g, " | "));
await p.getByRole("button", { name: "Book a call" }).first().click();
await p.waitForTimeout(800);
await p.locator("main button:not([disabled])[aria-pressed=false]").filter({ hasText: /^\d{1,2}$/ }).first().click();
await p.getByRole("button", { name: "10:30" }).click();
await p.getByRole("button", { name: "Video", exact: true }).click();
await p.screenshot({ path: `${out}/cta-${w}-3-booking.png`, fullPage: true });
await p.getByRole("button", { name: "Confirm video call" }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/cta-${w}-4-booked.png` });
console.log("booked:", (await p.locator("main [role=status]").innerText()).replace(/\n/g, " | "));
await p.getByRole("button", { name: /open full preview/ }).click();
await p.waitForTimeout(800);
await p.getByRole("button", { name: "Mobile" }).click().catch(() => {});
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/cta-${w}-5-preview-mobile-toggle.png` });
console.log("errors:", errors);
await b.close();
