// QA: full concept flow in a real browser. node scripts/test-flow.mjs <baseUrl> <outDir> [width] [fail]
import { chromium } from "@playwright/test";
const [base = "http://localhost:3457", out = ".", w = "1440", fail = "0"] = process.argv.slice(2);
const b = await chromium.launch({ channel: "chromium" });
const p = await b.newPage({ viewport: { width: +w, height: 900 } });
const errors = [];
p.on("pageerror", (e) => errors.push(e.message));
p.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const shot = (n) => p.screenshot({ path: `${out}/flow-${w}-${n}.png`, fullPage: false });
const say = async (text) => {
  const ta = p.locator("form textarea:visible").last();
  await ta.fill(text);
  await ta.press("Enter");
  await p.waitForTimeout(400);
  await p.locator("[role=status]").first().waitFor({ state: "detached", timeout: 15000 }).catch(() => {});
  await p.waitForTimeout(1300);
};
const tap = async (name) => {
  await p.getByRole("button", { name, exact: true }).first().click();
  await p.waitForTimeout(400);
  await p.locator("[role=status]").first().waitFor({ state: "detached", timeout: 15000 }).catch(() => {});
  await p.waitForTimeout(1300);
};
await p.goto(base + "/", { waitUntil: "networkidle" });
await p.evaluate(() => localStorage.clear());
await p.reload({ waitUntil: "networkidle" });
const hero = p.locator("section[aria-labelledby=hero-title] textarea");
await hero.fill("Fade Factory, a barbershop in Manchester");
await hero.press("Enter");
await p.waitForURL("**/concept" + (fail === "1" ? "" : ""));
if (fail === "1") await p.goto(base + "/concept?fail=1");
await p.waitForTimeout(3500);
await shot("01-q1");
await say("Skin fades, beard trims and hot towel shaves");
await say("Local customers looking for a fresh cut");
await say("Precise fades and a relaxed welcome");
await shot("02-q4");
await tap("Skip");
await shot("03-q5");
await tap("Book");
await say("Bold, modern and welcoming");
await shot("04-q7");
await tap("I have colours, but no logo");
await p.getByLabel("Your colours").fill("navy and gold");
await p.waitForTimeout(300);
await shot("05-colours");
await p.getByRole("button", { name: "Use colours" }).click();
await p.waitForTimeout(2500);
await p.getByRole("button", { name: /Show me my homepage/ }).click();
await p.waitForTimeout(500);
await shot("06-contact-errors");
await p.getByLabel("Name *").fill("Alex Taylor");
await p.getByLabel("Email *").fill("alex@example.com");
await p.getByLabel("Phone *").fill("07700 900123");
await p.getByRole("button", { name: /Show me my homepage/ }).click();
await p.waitForTimeout(6000);
await shot("07-loading");
await p.waitForTimeout(fail === "1" ? 2000 : 16000);
await shot("08-after-loading");
console.log("answers:", await p.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem("rc-concept")).state.answers)));
console.log("stage:", await p.evaluate(() => JSON.parse(localStorage.getItem("rc-concept")).state.stage));
console.log("errors:", errors.slice(0, 5));
await b.close();
